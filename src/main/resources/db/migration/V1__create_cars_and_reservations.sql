CREATE TABLE cars (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_name VARCHAR(100) NOT NULL,
    car_number VARCHAR(20) NOT NULL UNIQUE,
    daily_price NUMERIC(12, 0) NOT NULL CHECK (daily_price >= 0),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_id BIGINT NOT NULL REFERENCES cars (id),
    renter_name VARCHAR(50) NOT NULL,
    renter_phone VARCHAR(20) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    total_amount NUMERIC(12, 0) NOT NULL CHECK (total_amount >= 0),
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT chk_reservation_dates CHECK (end_date >= start_date)
);